
-- =========================================================
-- SUPPORT TICKET MANAGEMENT SYSTEM
-- PostgreSQL core schema
-- =========================================================

  -- Creating database 
  
  CREATE DATABASE support_ticket_db;

-- 1. USERS
  
CREATE TABLE users (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(256) NOT NULL,
    password_hash   TEXT NOT NULL,
    role            VARCHAR(10) NOT NULL DEFAULT 'USER',
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_users_email UNIQUE (email),

    CONSTRAINT ck_users_full_name
        CHECK (length(trim(full_name)) >= 2),

    CONSTRAINT ck_users_role
        CHECK (role IN ('USER', 'AGENT', 'ADMIN'))
);


-- 2. TICKETS
  
CREATE TABLE tickets (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject             VARCHAR(200) NOT NULL,
    description         TEXT NOT NULL,
    category            VARCHAR(30) NOT NULL DEFAULT 'Other',
    severity            VARCHAR(10) NOT NULL DEFAULT 'NORMAL',
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    created_by_id       INTEGER NOT NULL,
    assigned_agent_id   INTEGER NULL,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at         TIMESTAMPTZ NULL,

    CONSTRAINT fk_tickets_creator
        FOREIGN KEY (created_by_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tickets_assigned_agent
        FOREIGN KEY (assigned_agent_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_tickets_subject
        CHECK (length(trim(subject)) BETWEEN 3 AND 200),

    CONSTRAINT ck_tickets_description
        CHECK (length(trim(description)) BETWEEN 5 AND 10000),

    CONSTRAINT ck_tickets_category
        CHECK (category IN (
            'Technical',
            'Billing',
            'Account',
            'Access',
            'Other'
        )),

    CONSTRAINT ck_tickets_severity
        CHECK (severity IN ('HIGH', 'NORMAL')),

    CONSTRAINT ck_tickets_status
        CHECK (status IN (
            'OPEN',
            'IN_PROGRESS',
            'RESOLVED',
            'CLOSED'
        )),

    CONSTRAINT ck_tickets_resolved_at
        CHECK (
            (status = 'RESOLVED' AND resolved_at IS NOT NULL)
            OR
            (status <> 'RESOLVED' AND resolved_at IS NULL)
        )
);


-- 3. TICKET COMMENTS
  
CREATE TABLE ticket_comments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   INTEGER NOT NULL,
    user_id     INTEGER NOT NULL,
    message     VARCHAR(5000) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comments_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_comments_message
        CHECK (length(trim(message)) BETWEEN 1 AND 5000)
);


CREATE TABLE ticket_status_history (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id       INTEGER NOT NULL,
    changed_by_id   INTEGER NOT NULL,
    old_status      VARCHAR(20) NULL,
    new_status      VARCHAR(20) NOT NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note            VARCHAR(1000) NULL,

    CONSTRAINT fk_status_history_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES tickets(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_status_history_user
        FOREIGN KEY (changed_by_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_status_history_old_status
        CHECK (
            old_status IS NULL OR old_status IN (
                'OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'
            )
        ),

    CONSTRAINT ck_status_history_new_status
        CHECK (new_status IN (
            'OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'
        ))
);


-- Ticket lists filtered by status and ordered by creation date
CREATE INDEX ix_tickets_status_created_at
    ON tickets (status, created_at DESC);

-- Tickets belonging to a particular user
CREATE INDEX ix_tickets_created_by_created_at
    ON tickets (created_by_id, created_at DESC);

-- Active-ticket counts and assignment queries
CREATE INDEX ix_tickets_assigned_agent_status
    ON tickets (assigned_agent_id, status)
    WHERE assigned_agent_id IS NOT NULL;

-- Comment history for a ticket
CREATE INDEX ix_ticket_comments_ticket_created_at
    ON ticket_comments (ticket_id, created_at);

-- Case-insensitive email lookup support
-- The email column should also be normalized by the API.

CREATE INDEX ix_status_history_ticket_changed_at
    ON ticket_status_history (ticket_id, changed_at);


COMMIT;
